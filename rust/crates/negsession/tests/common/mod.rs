//! Shared helpers for the negsession integration tests.
#![allow(dead_code, clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};

use negkit::RgbImage;

static COUNTER: AtomicU64 = AtomicU64::new(0);

/// A fresh, empty scratch directory per call (the suites run concurrently).
pub fn scratch_dir(label: &str) -> PathBuf {
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let dir = std::env::temp_dir().join(format!(
        "negsession-{label}-{}-{nanos}-{n}",
        std::process::id()
    ));
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// NegPy's synthetic-grid negative (1600×1066, integer-hash formula regenerated by negkit) —
/// a frame `prepare` is known to meter. Long edge > 1536, so a session built on it downsamples
/// to the proxy and keeps the native buffer as its medium tier.
pub fn synthetic_negative() -> RgbImage {
    negkit::fixtures::synthetic_grid_input().expect("synthetic grid")
}

/// Nearest-neighbour 2× upscale — a stand-in "full decode" whose dims differ from the preview.
pub fn upscale2x(img: &RgbImage) -> RgbImage {
    let (w, h) = (img.width * 2, img.height * 2);
    RgbImage::new_with(w, h, |data| {
        for y in 0..h {
            for x in 0..w {
                let p = img.pixel(x / 2, y / 2).unwrap();
                let i = (y * w + x) * 3;
                data[i..i + 3].copy_from_slice(&p);
            }
        }
    })
    .unwrap()
}

/// Encoded 32×24 gradient (values already in the working TRC domain) — the Swift
/// `AuditExporterWriteTests` buffer.
pub fn encoded_gradient() -> RgbImage {
    let (w, h) = (32usize, 24usize);
    RgbImage::new_with(w, h, |data| {
        for y in 0..h {
            for x in 0..w {
                let i = (y * w + x) * 3;
                data[i] = x as f32 / (w - 1) as f32;
                data[i + 1] = y as f32 / (h - 1) as f32;
                data[i + 2] = 0.5;
            }
        }
    })
    .unwrap()
}
